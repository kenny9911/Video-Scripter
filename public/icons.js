/** An <svg> element. Decorative by default: the control it sits in carries the label. */
export function icon(name, size = 18) {
  const wrap = document.createElement('span');
  wrap.innerHTML = `<svg class="icon" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${P[name] || ''}</svg>`;
  return wrap.firstChild;
}

/** Put an icon at the start of every element marked data-icon="name" (optionally data-icon-size). */
export function hydrateIcons(root = document) {
  for (const el of root.querySelectorAll('[data-icon]')) {
    if (el.querySelector(':scope > svg.icon')) continue;
    el.prepend(icon(el.dataset.icon, Number(el.dataset.iconSize) || 18));
  }
}
